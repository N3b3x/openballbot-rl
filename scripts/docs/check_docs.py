"""Check that the links, image paths and backticked file paths in the front-page documents exist.

    python scripts/docs/check_docs.py                       # the default set of documents
    python scripts/docs/check_docs.py Readme.md docs/pipeline.md

For every document it checks:
  - markdown links and images  [text](target) and ![alt](target): relative targets must exist, #fragments must match a heading
    (GitHub slug rules) or an explicit id in the target markdown file;
  - HTML  src= / srcset= / href=  attributes (the <picture> blocks): relative targets must exist;
  - backticked tokens that look like paths (a slash, or a known file extension): they must exist relative to the document, to the
    repository root, or (for a bare file name) somewhere in the repository. Tokens with <>, *, {}, spaces, "..." or a leading
    "--" or "$" are treated as templates, commands or flags and skipped;
  - em and en dashes, which the style rules of the project forbid.
External http(s) links are not fetched; the hosts are listed with --external. Exit code 1 if anything is broken.
"""
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT = ["Readme.md", "docs/README.md", "docs/pipeline.md", "docs/research/README.md", "ros2/README.md", "CONTRIBUTING.md"]
SKIP_DIRS = {".git", "node_modules", "__pycache__", ".venv", ".claude"}
EXTS = (".py", ".md", ".yaml", ".yml", ".json", ".xml", ".html", ".svg", ".webp", ".png", ".sh", ".toml", ".txt", ".csv", ".cff",
        ".onnx", ".npz", ".ts", ".tex", ".cfg", ".xacro", ".launch", ".pdf", ".mp4")
# files that are generated by a command or git-ignored by design: a backticked mention is not a broken reference
GENERATED = {"model.pt", "log.csv", "falls_by.csv", "args.json", "battery.json", "bundle.json", "actor.onnx", "actor.ts",
             "actor_weights.npz", "parity_rollout.npz", "study.json", "site_crosscheck.md", "tracking_summary.csv"}

# illustrative or upstream names that are intentionally not files of this repository
ILLUSTRATIVE = {"../mjx_port/.venv/Scripts/python.exe", "bbot.xml", "bbot_env.py", "test/data/",
                "ballbot_gym/rewards/my_reward.py", "ballbot_gym/terrain/my_terrain.py", "ballbot_rl/policies/my_policy.py"}

_BASENAMES = None


def basenames():
    global _BASENAMES
    if _BASENAMES is None:
        _BASENAMES = set()
        for dp, dn, fn in os.walk(ROOT):
            dn[:] = [d for d in dn if d not in SKIP_DIRS]
            _BASENAMES.update(fn)
            _BASENAMES.update(dn)
    return _BASENAMES


def slug(heading):
    h = re.sub(r"<[^>]+>", "", heading).strip().lower()
    h = re.sub(r"`", "", h)
    h = re.sub(r"[^\w\- ]", "", h, flags=re.UNICODE)
    return h.replace(" ", "-")


def anchors(path):
    out, seen = set(), {}
    try:
        text = path.read_text(encoding="utf-8")
    except Exception:
        return out
    in_code = False
    for line in text.splitlines():
        if line.startswith("```"):
            in_code = not in_code
        if in_code:
            continue
        m = re.match(r"#{1,6}\s+(.*?)\s*#*\s*$", line)
        if m:
            s = slug(m.group(1))
            n = seen.get(s, 0)
            seen[s] = n + 1
            out.add(s if n == 0 else f"{s}-{n}")
    out.update(re.findall(r'id="([^"]+)"', text))
    return out


def resolve(doc, target):
    """Return the existing path for a relative target, or None."""
    t = target.split("#")[0].split("?")[0]
    if not t:
        return doc
    p = (doc.parent / t).resolve()
    return p if p.exists() else None


def looks_like_path(tok):
    if re.search(r"[<>*{}\s$|;=,]|\.\.\.|^--|^-", tok):
        return False
    if tok.startswith(("http", "git@", "/")) or tok.endswith(("/..", ":")):
        return False
    return "/" in tok or tok.lower().endswith(EXTS)


def check(doc_rel):
    doc = ROOT / doc_rel
    errs = []
    if not doc.exists():
        return [f"{doc_rel}: document missing"]
    text = doc.read_text(encoding="utf-8")
    # drop fenced code blocks for the backtick scan (commands there are not references), keep them for dash scan
    prose = re.sub(r"```.*?```", "", text, flags=re.S)
    targets = []
    for m in re.finditer(r"!?\[[^\]]*\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)", prose):
        targets.append(m.group(1))
    for m in re.finditer(r'(?:src|srcset|href)="([^"]+)"', prose):
        targets.append(m.group(1))
    for t in targets:
        if re.match(r"(https?:|mailto:)", t):
            continue
        p = resolve(doc, t)
        if p is None:
            errs.append(f"{doc_rel}: broken link or image path: {t}")
            continue
        if "#" in t and p.suffix == ".md":
            frag = t.split("#", 1)[1]
            if frag and frag not in anchors(p):
                errs.append(f"{doc_rel}: missing anchor {t}")
    for m in re.finditer(r"`([^`\n]+)`", prose):
        tok = m.group(1).strip()
        if not looks_like_path(tok):
            continue
        tok = tok.rstrip(".,;)")
        if tok in ILLUSTRATIVE or Path(tok).name in GENERATED:
            continue
        cands = [doc.parent / tok, ROOT / tok]
        if any(c.exists() for c in cands):
            continue
        if "/" not in tok and tok in basenames():
            continue
        if "/" in tok and Path(tok).name in basenames() and tok.startswith(("outputs/", "..")) is False and "<" in tok:
            continue
        errs.append(f"{doc_rel}: backticked path not found: {tok}")
    for i, line in enumerate(text.splitlines(), 1):
        if "—" in line or "–" in line:
            errs.append(f"{doc_rel}:{i}: em or en dash")
    return errs


def main(argv):
    docs = [a for a in argv if not a.startswith("--")] or DEFAULT
    allerrs = []
    for d in docs:
        e = check(d)
        print(f"{d}: {'ok' if not e else str(len(e)) + ' problem(s)'}")
        allerrs += e
    for e in allerrs:
        print("  " + e)
    if "--external" in argv:
        hosts = set()
        for d in docs:
            if (ROOT / d).exists():
                hosts.update(re.findall(r"https?://([^/\s)\"'>]+)", (ROOT / d).read_text(encoding="utf-8")))
        print("external hosts:", ", ".join(sorted(hosts)))
    return 1 if allerrs else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
