"""Export the current parametric robot picture model to JSON for the web site's home page hero.

The robot is generated by ballbot_layout.py (wheel layout) and layout_render.py (visual geoms). This script compiles those geoms with MuJoCo and writes every
compiled geom (type, size, world position, world quaternion, colour, part tag) to site/data/robot_model.json. The hero script site/assets/js/hero3d.js loads
that file and builds the 3-D robot from it, so the web robot follows the Python model. It also renders the static fallback picture the hero shows when the
JSON or WebGL is unavailable (site/assets/img/hero-robot-poster.png, transparent background).

ONE COMMAND regenerates both files after any change to the model (run from the repository root):

  experiments/mjx_port/.venv/Scripts/python.exe scripts/study/export_robot_json.py

Options:
  export_robot_json.py SPEC.yaml        use a robot spec (the same yaml that `robot_spec.py show` takes) instead of the default picture robot
  --out PATH                            JSON path (default site/data/robot_model.json)
  --poster PATH                         fallback picture path (default site/assets/img/hero-robot-poster.png)
  --no-poster                           skip the picture (no OpenGL needed)

Default robot: L = ballbot_layout.family("robot", 3, arr_theta=112.0); L["arms"] = True   (the one used in the videos).

Conventions in the JSON (MuJoCo's): metres, z up, the robot's front is +x, the ball centre is at (0, 0, R). quat is (w, x, y, z). size is MuJoCo's:
sphere [r], capsule and cylinder [radius, half-length] along the geom's local z, box and ellipsoid [half-x, half-y, half-z]. part is "ball" (the first 4 geoms),
"wheel" (the spinning part of a drive unit: two roller rings and the hub, with its wheel index) or "body" (everything else, fixed to the body).
Each entry of "wheels" gives the hub centre, the spin axis, the outward contact normal and the drive tangent, so a viewer can spin the wheel consistently
with the ball: rate = -(R / rw) * dot(cross(w_rel, normal), tangent) / dot(cross(axis, normal), tangent), w_rel = ball angular velocity relative to the body.

Simulation-only visual model; it is not the physics model.
"""
import argparse
import datetime
import json
import sys
from pathlib import Path

import numpy as np
import mujoco

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE))
import ballbot_layout as BL  # noqa: E402
import layout_render as LR  # noqa: E402

N_BALL = 4                                                # layout_render.build(): the ball sphere and its three seam discs come first
TYPES = {mujoco.mjtGeom.mjGEOM_SPHERE: "sphere", mujoco.mjtGeom.mjGEOM_CAPSULE: "capsule", mujoco.mjtGeom.mjGEOM_CYLINDER: "cylinder",
         mujoco.mjtGeom.mjGEOM_BOX: "box", mujoco.mjtGeom.mjGEOM_ELLIPSOID: "ellipsoid", mujoco.mjtGeom.mjGEOM_MESH: "mesh"}
NSIZE = dict(sphere=1, capsule=2, cylinder=2, box=3, ellipsoid=3, mesh=3)
LIGHTS = ('<visual><global offwidth="2400" offheight="2400"/><headlight ambient="0.42 0.42 0.44" diffuse="0.55 0.55 0.55" specular="0.15 0.15 0.15"/></visual>')


def default_layout():
    L = BL.family("robot", 3, arr_theta=112.0); L["arms"] = True
    return L


def spec_layout(path):
    import yaml
    import robot_spec as RS
    return RS.spec_to_layout(yaml.safe_load(open(path)))


def compile_geoms(geoms, extra=""):
    """The geoms in a minimal world-only model, as layout_render.layout_xml does but without the floor, so ngeom equals the number of generated geoms."""
    m = mujoco.MjModel.from_xml_string(f"<mujoco>{extra}<worldbody>{chr(10).join(geoms)}</worldbody></mujoco>")
    d = mujoco.MjData(m); mujoco.mj_forward(m, d)
    return m, d


def wheel_frames(L):
    """Hub centre, spin axis (the shaft, up along the ball's meridian), outward contact normal and drive tangent of every wheel; the same maths as layout_render.build()."""
    R, rw = L["R"], L["rw"]; c = np.array([0.0, 0.0, R]); p, t, _ = BL.geometry(L); Z = np.array([0.0, 0.0, 1.0]); out = []
    for i in range(L["n"]):
        pn = p[i] / np.linalg.norm(p[i]); ax = Z - (Z @ pn) * pn; ax /= np.linalg.norm(ax)
        out.append(dict(index=i, hub=c + (R + rw) * pn, axis=ax, normal=pn, tangent=t[i], radius=rw, phi_deg=float(L["phi"][i]), theta_deg=float(L["theta"][i])))
    return out


def which_wheel(typ, pos, zaxis, size, wheels, L):
    """Index of the wheel this geom spins with, or None. Spinning parts: the two wheel discs, their rollers and the hub; all lie within the wheel's width and radius
    around the hub (the motor and gearbox start further along the shaft and are fixed to the body)."""
    rw, ww = L["rw"], L["ww"]
    if typ not in ("cylinder", "capsule"): return None
    for w in wheels:
        r = pos - w["hub"]; axial = abs(r @ w["axis"]); radial = np.linalg.norm(r - (r @ w["axis"]) * w["axis"])
        if axial > ww * 0.3 or radial > rw * 0.9: continue
        if typ == "cylinder" and abs(zaxis @ w["axis"]) > 0.995 and radial < 2e-4 and size[0] <= rw * 0.8 + 1e-5: return w["index"]      # disc or hub
        if typ == "capsule" and abs(radial - rw * 0.87) < 2e-4 and abs(size[0] - rw * 0.13) < 2e-5: return w["index"]              # roller
    return None


def export(L, out, source):
    geoms, info = LR.build(L)
    m, d = compile_geoms(geoms)
    assert m.ngeom == len(geoms), (m.ngeom, len(geoms))
    wheels = wheel_frames(L); names = {tuple(round(float(x), 3) for x in v.split()): k for k, v in LR.COL.items()}; rows = []; q = np.zeros(4); zmax = 0.0; rmax = 0.0
    for i in range(m.ngeom):
        typ = TYPES.get(mujoco.mjtGeom(int(m.geom_type[i])))
        assert typ is not None, f"geom {i}: type {int(m.geom_type[i])} is not exported"
        pos = d.geom_xpos[i].copy(); mat = d.geom_xmat[i].copy(); mujoco.mju_mat2Quat(q, mat); size = m.geom_size[i][:NSIZE[typ]]; rgba = m.geom_rgba[i]
        g = dict(i=i, type=typ, size=[round(float(x), 6) for x in size], pos=[round(float(x), 6) for x in pos], quat=[round(float(x), 7) for x in q],
                 rgba=[round(float(x), 4) for x in rgba], color=names.get(tuple(round(float(x), 3) for x in rgba[:3]), "custom"))
        if i < N_BALL: g["part"] = "ball"
        else:
            wi = which_wheel(typ, pos, mat.reshape(3, 3)[:, 2], size, wheels, L)
            g["part"] = "body" if wi is None else "wheel"
            if wi is not None: g["wheel"] = wi
        if typ == "mesh":                                 # not produced by layout_render today; exported so a future mesh part still shows up
            mid = int(m.geom_dataid[i]); v0, nv = int(m.mesh_vertadr[mid]), int(m.mesh_vertnum[mid]); f0, nf = int(m.mesh_faceadr[mid]), int(m.mesh_facenum[mid])
            g["vertices"] = np.round(m.mesh_vert[v0:v0 + nv], 5).ravel().tolist(); g["faces"] = m.mesh_face[f0:f0 + nf].ravel().tolist()
        zmax = max(zmax, float(pos[2] + m.geom_rbound[i])); rmax = max(rmax, float(np.hypot(pos[0], pos[1]) + m.geom_rbound[i])); rows.append(g)
    per = [sum(1 for g in rows if g.get("wheel") == w["index"]) for w in wheels]
    assert all(k == 23 for k in per), f"expected 23 spinning geoms per wheel (2 discs, 20 rollers, 1 hub), found {per}"
    assert [g["type"] for g in rows[:N_BALL]] == ["sphere", "cylinder", "cylinder", "cylinder"], "the first 4 geoms are no longer the ball and its seams"
    counts = {}
    for g in rows: counts[g["part"]] = counts.get(g["part"], 0) + 1
    vec = lambda a: [round(float(x), 6) for x in a]
    doc = dict(
        meta=dict(layout=L["name"], ball_radius=float(L["R"]), wheel_count=int(L["n"]), wheel_radius=float(L["rw"]), wheel_width=float(L["ww"]), drive=L["drive"],
                  arms=bool(L.get("arms", True)), guard_reach_deg=(None if L["arr_theta"] is None else float(L["arr_theta"])), body_half_width=float(L["body_r"]),
                  body_height=float(L["body_h"]), collar_z=round(float(info["collar_z"]), 5), top_z=round(float(info["top_z"]), 5), height=round(zmax, 4),
                  radius=round(rmax, 4), ngeom=int(m.ngeom), parts=counts, units="m", up="z", front="+x", quat_order="wxyz",
                  generated=datetime.date.today().isoformat(), source="scripts/study/export_robot_json.py" + (f" {source}" if source else ""),
                  generator="scripts/study/layout_render.py build() on a scripts/study/ballbot_layout.py layout", note="Simulation-only visual model; not the physics model."),
        wheels=[dict(index=w["index"], hub=vec(w["hub"]), axis=vec(w["axis"]), normal=vec(w["normal"]), tangent=vec(w["tangent"]), radius=float(w["radius"]),
                     phi_deg=w["phi_deg"], theta_deg=w["theta_deg"]) for w in wheels],
        geoms=rows)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(doc, separators=(",", ":")).replace('},{"i":', '},\n{"i":') + "\n", encoding="utf-8")
    print(f"saved {out}  ({m.ngeom} geoms: {counts}, {out.stat().st_size / 1024:.0f} kB)")
    return geoms, doc


def poster(geoms, doc, out, w=900, h=1000):
    """The fallback picture: the same geoms from the front quarter, on a transparent background (so it sits on the light and the dark theme)."""
    from PIL import Image
    m, d = compile_geoms(geoms, LIGHTS + '<worldbody><light pos="0.9 -0.9 2.2" dir="-0.35 0.35 -1" diffuse="0.75 0.75 0.75"/></worldbody>')
    H = doc["meta"]["height"]; r = mujoco.Renderer(m, 2 * h, 2 * w); cam = mujoco.MjvCamera(); cam.type = mujoco.mjtCamera.mjCAMERA_FREE
    cam.lookat[:] = [0, 0, H * 0.47]; cam.distance = H * 1.55; cam.azimuth = 152; cam.elevation = -8
    r.update_scene(d, camera=cam); rgb = r.render().copy()
    r.enable_segmentation_rendering(); r.update_scene(d, camera=cam); seg = r.render()[:, :, 0]; r.close()
    a = np.where(seg >= 0, 255, 0).astype(np.uint8)
    img = Image.fromarray(np.dstack([rgb, a]), "RGBA").resize((w, h), Image.LANCZOS)
    out.parent.mkdir(parents=True, exist_ok=True); img.save(out, optimize=True); print(f"saved {out}  ({out.stat().st_size / 1024:.0f} kB)")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("spec", nargs="?", help="optional robot spec yaml (as for robot_spec.py show)")
    ap.add_argument("--out", default=str(ROOT / "site" / "data" / "robot_model.json"))
    ap.add_argument("--poster", default=str(ROOT / "site" / "assets" / "img" / "hero-robot-poster.png"))
    ap.add_argument("--no-poster", action="store_true")
    a = ap.parse_args()
    L = spec_layout(a.spec) if a.spec else default_layout()
    geoms, doc = export(L, Path(a.out), Path(a.spec).as_posix() if a.spec else "")
    if not a.no_poster: poster(geoms, doc, Path(a.poster))


if __name__ == "__main__":
    main()
